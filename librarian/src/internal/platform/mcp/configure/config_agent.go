package mcp

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/sentzunhat/hawp/librarian/src/internal/infrastructure/filesystem"
)

const hawpAgentMarker = "<!-- Generated by HAWP mcp configure. -->"

var hawpCopilotTools = []string{
	"hawp/hawp_search",
	"hawp/hawp_usage",
	"hawp/hawp_work_intake",
	"hawp/hawp_work_new",
	"hawp/hawp_work_validate",
	"hawp/hawp_work_doc",
	"hawp/hawp_work_reshape",
}

func githubCopilotAgentContent() []byte {
	var content strings.Builder
	content.WriteString("---\n")
	content.WriteString("name: HAWP\n")
	content.WriteString("description: Use HAWP MCP tools for repository workflow and work records\n")
	content.WriteString("target: github-copilot\n")
	content.WriteString("tools:\n")
	for _, tool := range hawpCopilotTools {
		fmt.Fprintf(&content, "  - %s\n", tool)
	}
	content.WriteString("---\n\n")
	content.WriteString(hawpAgentMarker + "\n")
	content.WriteString("Use the HAWP MCP tools listed for this agent for repository workflow operations.\n")
	content.WriteString("Tool availability does not grant approval. Follow the client's normal confirmation prompts, especially for tools that create or edit work records.\n")
	content.WriteString("If a HAWP tool is unavailable, report that clearly before using a repository-local CLI fallback.\n")
	return []byte(content.String())
}

func writeGitHubCopilotAgent(repoRoot, path string) error {
	if err := filesystem.RejectSymlinkAncestors(repoRoot, path); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	perm, err := managedFilePerm(path, 0o644)
	if err != nil {
		return err
	}
	return filesystem.AtomicWriteFile(repoRoot, path, githubCopilotAgentContent(), perm)
}
